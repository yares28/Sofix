// Builds the loadable extension from manifest.template.json and the repo's .env.
//   node extension/scripts/configure.mjs
// Writes manifest.json (the app's address filled in) and config.js (the app address, the extension token and the
// Vercel bypass secret). Both are git-ignored: config.js holds secrets. Chrome loads the extension/ folder itself.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const extensionDir = path.resolve(here, "..");
const repoRoot = path.resolve(extensionDir, "..");
const args = process.argv.slice(2);
const option = (key, fallback) => args.includes(key) ? args[args.indexOf(key) + 1] : fallback;
const envFile = path.resolve(option("--env-file", path.join(repoRoot, ".env")));
const output = path.resolve(option("--output", extensionDir));

const env = Object.fromEntries(
  fs
    .readFileSync(envFile, "utf8")
    .split(/\r?\n/)
    .filter((line) => line.trim() && !line.trim().startsWith("#") && line.includes("="))
    .map((line) => {
      const i = line.indexOf("=");
      return [line.slice(0, i).trim(), line.slice(i + 1).trim().replace(/^["']|["']$/g, "")];
    }),
);

const missing = ["APP_URL", "EXTENSION_TOKEN", "VERCEL_BYPASS_SECRET"].filter((key) => !env[key]);
if (missing.length) {
  console.error(`Missing in .env: ${missing.join(", ")}`);
  process.exit(1);
}

function appOrigin(value) {
  try {
    const url = new URL(value);
    const local = url.protocol === "http:" && ["localhost", "127.0.0.1"].includes(url.hostname);
    if ((!local && url.protocol !== "https:") || url.username || url.password || url.hostname.includes("*") || url.pathname !== "/" || url.search || url.hash) throw new Error();
    return url.origin;
  } catch {
    throw new Error("APP_URL and APP_ORIGINS must contain exact HTTPS origins (or local HTTP), with no embedded authentication or paths.");
  }
}
const origin = appOrigin(env.APP_URL);
const allowedOrigins = [...new Set([origin, ...option("--origins", env.APP_ORIGINS ?? "").split(",").map(value => value.trim()).filter(Boolean).map(appOrigin)])];
const manifest = JSON.parse(fs.readFileSync(path.join(extensionDir, "manifest.template.json"), "utf8").replaceAll("__APP_ORIGIN__", origin));
manifest.host_permissions = [...new Set([...manifest.host_permissions, ...allowedOrigins.map(value => `${value}/*`)])];
manifest.externally_connectable.matches = [...allowedOrigins.map(value => `${value}/*`), "http://localhost/*", "http://127.0.0.1/*"];
fs.writeFileSync(path.join(output, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
fs.writeFileSync(
  path.join(output, "config.js"),
  "// Generated by scripts/configure.mjs from the repo's .env. Git-ignored: it holds secrets.\n" +
    `export const CONFIG = ${JSON.stringify({ appUrl: origin, allowedOrigins, token: env.EXTENSION_TOKEN, bypass: env.VERCEL_BYPASS_SECRET })};\n`,
);
console.log(`Configured for ${origin}, and for http://localhost and http://127.0.0.1 on any port.`);
console.log(`Load this folder in chrome://extensions (Developer mode > Load unpacked): ${output}`);
